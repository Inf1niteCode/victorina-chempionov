async function main() {
  console.log("🌱 Начало сидирования базы данных...\n");

  // Подсчёт статистики
  const freeThemes = themes.filter((t) => t.isFree);
  const paidThemes = themes.filter((t) => !t.isFree);
  console.log(`📚 Тем всего: ${themes.length}`);
  console.log(`   ✅ Бесплатных: ${freeThemes.length}`);
  console.log(`   💰 Платных: ${paidThemes.length}`);
  console.log(`   ❓ Вопросов всего: ${themes.length * 5}\n`);

  let themesCreated = 0;
  let questionsCreated = 0;

  for (const themeData of themes) {
    // Создаём или обновляем тему
    const existing = await prisma.theme.findFirst({
      where: { name: themeData.name },
    });

    let theme;
    if (existing) {
      theme = await prisma.theme.update({
        where: { id: existing.id },
        data: {
          category: themeData.category,
          isFree: themeData.isFree,
        },
      });
      console.log(`  ♻️  Обновлена: [${themeData.category}] ${themeData.name}`);
    } else {
      theme = await prisma.theme.create({
        data: {
          name: themeData.name,
          category: themeData.category,
          isFree: themeData.isFree,
        },
      });
      themesCreated++;
      console.log(
        `  ✨ Создана: [${themeData.category}] ${themeData.name} (${themeData.isFree ? "БЕСПЛАТНО" : "100 ₽"})`,
      );
    }

    // Создаём только новые вопросы (старые не трогаем)
    const existingQuestions = await prisma.question.findMany({
      where: { themeId: theme.id },
      select: { text: true },
    });
    const existingTexts = new Set(existingQuestions.map((q) => q.text));

    for (const q of themeData.questions) {
      if (!existingTexts.has(q.text)) {
        await prisma.question.create({
          data: {
            text: q.text,
            answer: q.answer,
            points: q.points,
            themeId: theme.id,
          },
        });
        questionsCreated++;
      }
    }
  }

  console.log("\n✅ Сидирование завершено!");
  console.log(`   Тем создано: ${themesCreated}`);
  console.log(`   Вопросов создано: ${questionsCreated}`);

  // Вывод итоговой статистики по категориям
  console.log("\n📊 Статистика по категориям:");
  const categories = ["ИСТОРИЯ", "НАУКА", "КУЛЬТУРА", "СПОРТ", "ГЕОГРАФИЯ"];
  for (const cat of categories) {
    const catThemes = themes.filter((t) => t.category === cat);
    const free = catThemes.filter((t) => t.isFree).length;
    console.log(
      `   ${cat}: ${catThemes.length} тем (${free} бесплатных, ${catThemes.length - free} платных)`,
    );
  }
}

main()
  .catch((e) => {
    console.error("❌ Ошибка сидирования:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
